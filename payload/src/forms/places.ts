let countries: [string, string][] | null = null
/** Every country, by name, with the United States first. */
export function countryOptions(): [string, string][] {
  if (countries) return countries
  const names = new Intl.DisplayNames(['en'], { type: 'region' })
  const all = REGIONS.map((c) => [c, names.of(c) ?? c] as [string, string]).sort((a, b) =>
    a[1].localeCompare(b[1]),
  )
  countries = [['US', 'United States'], ...all.filter(([c]) => c !== 'US')]
  return countries
}
